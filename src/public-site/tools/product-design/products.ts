export function createStarterPresetLayers(
  presetId: 'logo-only' | 'badge-pro' | 'minimal-brand' | 'promo-banner',
  product: ProductBase,
  existingLogoSrc?: string,
): DesignLayer[] {
  const area = product.printArea;
  const cx = area.x + area.width / 2;
  const cy = area.y + area.height / 2;
  const logoSrc = existingLogoSrc || '/brand/visualcorp-symbol.png';
  const baseLayer = getDefaultLogoLayer(product);

  if (presetId === 'logo-only') {
    return [{ ...baseLayer, src: logoSrc, x: cx, y: cy, size: Math.min(28, area.width * 0.56) }];
  }

  if (presetId === 'badge-pro') {
    const badgeSize = Math.min(34, area.width * 0.78);
    return [
      {
        ...baseLayer,
        id: 'preset-ring',
        kind: 'circle',
        name: 'Sello circular',
        src: undefined,
        x: cx,
        y: cy,
        size: badgeSize,
        color: '#111524',
        strokeColor: '#e5007e',
        strokeWidth: 4,
        opacity: 92,
      },
      {
        ...baseLayer,
        id: 'brand-logo',
        kind: 'image',
        name: 'Logo principal',
        src: logoSrc,
        x: cx,
        y: cy - area.height * 0.06,
        size: badgeSize * 0.44,
      },
      {
        ...baseLayer,
        id: 'preset-arc-text',
        kind: 'text',
        name: 'Texto curvo',
        src: undefined,
        text: 'EDICIÓN ESPECIAL',
        x: cx,
        y: cy + area.height * 0.16,
        size: badgeSize * 0.68,
        color: '#ffffff',
        fontFamily: 'DM Sans',
        letterSpacing: 1.5,
        textCurve: -26,
      },
    ];
  }

  if (presetId === 'promo-banner') {
    return [
      {
        ...baseLayer,
        id: 'preset-band',
        kind: 'badge',
        name: 'Cápsula destacada',
        src: undefined,
        x: cx,
        y: cy + area.height * 0.18,
        size: Math.min(36, area.width * 0.84),
        scaleY: 0.42,
        color: '#e5007e',
        opacity: 96,
      },
      {
        ...baseLayer,
        id: 'brand-logo',
        kind: 'image',
        name: 'Logo principal',
        src: logoSrc,
        x: cx,
        y: cy - area.height * 0.14,
        size: Math.min(24, area.width * 0.46),
      },
      {
        ...baseLayer,
        id: 'preset-cta-text',
        kind: 'text',
        name: 'Titular',
        src: undefined,
        text: 'TU MARCA AQUÍ',
        x: cx,
        y: cy + area.height * 0.18,
        size: Math.min(34, area.width * 0.78),
        color: '#ffffff',
        fontFamily: 'Impact',
        letterSpacing: 1.5,
      },
    ];
  }

  // minimal-brand
  return [
    {
      ...baseLayer,
      id: 'brand-logo',
      kind: 'image',
      name: 'Logo principal',
      src: logoSrc,
      x: cx,
      y: cy - area.height * 0.08,
      size: Math.min(22, area.width * 0.44),
    },
    {
      ...baseLayer,
      id: 'preset-line',
      kind: 'line',
      name: 'Línea acento',
      src: undefined,
      x: cx,
      y: cy + area.height * 0.11,
      size: Math.min(24, area.width * 0.54),
      color: '#4de1ff',
      opacity: 95,
    },
    {
      ...baseLayer,
      id: 'preset-brand-text',
      kind: 'text',
      name: 'Nombre de marca',
      src: undefined,
      text: 'VISUAL CORP',
      x: cx,
      y: cy + area.height * 0.22,
      size: Math.min(30, area.width * 0.72),
      color: '#ffffff',
      fontFamily: 'DM Sans',
      letterSpacing: 3,
      textShadow: true,
    },
  ];
}
