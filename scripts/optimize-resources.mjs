import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = process.cwd();
const sourceRoot = path.join(root, 'Recursos (no borrar)');
const publicRoot = path.join(root, 'public');
const manifestFile = path.join(root, 'src', 'data', 'resourceManifest.js');

const slugify = (value) => String(value)
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-|-$/g, '');

function destinationFor(relativeFile) {
  const parts = relativeFile.split(path.sep);
  const group = parts[0] || '';
  const subGroup = parts[1] || '';
  const file = parts.at(-1);
  if (group === 'Marca Gigaprint' && subGroup === 'Logo Giga') return ['brand', 'logos'];
  if (group === 'Marca Gigaprint' && subGroup === 'Masctota Gigalito') return ['brand', 'mascot'];
  if (group === 'Marca Gigaprint' && subGroup === 'Productos') return ['media', 'products'];
  if (file.toLowerCase().includes('milagro')) return ['media', 'seasonal', 'milagro'];
  if (group === 'Marca Gigaprint' && subGroup === 'Recursos Varios') return ['media', 'resources'];
  if (group === 'Recursos Varios') return ['media', 'resources'];
  return ['media', 'showcase'];
}

async function walk(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(absolute));
    else files.push(absolute);
  }
  return files;
}

async function main() {
  const sourceFiles = (await walk(sourceRoot)).filter((file) => /\.(png|jpe?g|webp|svg)$/i.test(file));
  const manifest = [];

  for (const sourceFile of sourceFiles) {
    const relative = path.relative(sourceRoot, sourceFile);
    const sourceName = path.basename(sourceFile);
    const ext = path.extname(sourceName).toLowerCase();
    const stem = slugify(path.basename(sourceName, ext)) || 'recurso';
    const [folder, ...rest] = destinationFor(relative);
    const destinationDirectory = path.join(publicRoot, folder, ...rest);
    await fs.mkdir(destinationDirectory, { recursive: true });

    const outputName = `${stem}.${ext === '.svg' ? 'svg' : 'webp'}`;
    const outputFile = path.join(destinationDirectory, outputName);

    if (ext === '.svg') await fs.copyFile(sourceFile, outputFile);
    else await sharp(sourceFile, { limitInputPixels: false })
      .rotate()
      .resize({ width: 2400, height: 2400, fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 84, effort: 5 })
      .toFile(outputFile);

    const outputPath = `/${path.relative(publicRoot, outputFile).split(path.sep).join('/')}`;
    manifest.push({ original: relative.split(path.sep).join('/'), path: outputPath, name: sourceName, type: ext === '.svg' ? 'svg' : 'image' });
  }

  manifest.sort((a, b) => a.path.localeCompare(b.path));
  const source = `// Generated by scripts/optimize-resources.mjs. Do not edit manually.\nimport { assetPath } from './media';\n\nexport const resourceManifest = ${JSON.stringify(manifest, null, 2)};\n\nexport const resourceUrls = resourceManifest.map((item) => ({ ...item, url: assetPath(item.path) }));\n\nexport const resources = Object.fromEntries(resourceUrls.map((item) => [item.path, item.url]));\n`;
  await fs.writeFile(manifestFile, source, 'utf8');
  console.log(`Prepared ${manifest.length} resources in public/ and wrote ${path.relative(root, manifestFile)}.`);
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
